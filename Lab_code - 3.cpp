// ---------- Завдання 1: If20 ----------
void task_if20() {
    double A, B, C;
    cout << "************* If 20 *****************" << endl;
    cout << "Введіть координати точок A, B, C: ";
    cin >> A >> B >> C;
    if (!cin) { // перевірка коректності введення
        cout << "Помилка: введено не числові дані!" << endl;
        return;
    }
    double dB = fabs(B - A); // відстань від A до B
    double dC = fabs(C - A); // відстань від A до C
    if (dB < dC)
        cout << "Ближче точка B = " << B << ", відстань = " << dB << endl;
    else if (dC < dB)
        cout << "Ближче точка C = " << C << ", відстань = " << dC << endl;
    else // відстані рівні
        cout << "Точки B і C рівновіддалені від A, відстань = " << dB << endl;
}

// ---------- Завдання 2: геометрія, варіант 10 ----------
// Система координат: вісь Ox проходить по верхній стороні квадрата, вісь Oy - через
// його центр. Квадрат: |x| < a/2, -a < y < 0. Вписане коло: центр (0, -a/2), R = a/2.
// Діагональ квадрата: y = x - a/2.
// Коричнева область (10 вар.) складається з трьох частин:
//  1) всередині кола, нижче діагоналі, ліворуч від осі Oy;
//  2) поза колом у квадраті, нижче діагоналі, вище рівня y = -a/2 (правий верхній куток);
//  3) поза колом у квадраті, вище діагоналі, нижче рівня y = -a/2 (лівий нижній куток).
void task_geom10() {
    double a, x, y;
    cout << "************* Geom 10 *****************" << endl;
    cout << "Введіть сторону квадрата a: ";
    cin >> a;
    if (!cin || a <= 0) { // перевірка сторони
        cout << "Некоректні дані! a має бути додатним числом." << endl;
        return;
    }
    cout << "Введіть координати точки (x, y): ";
    cin >> x >> y;
    if (!cin) {
        cout << "Не числові дані!" << endl;
        return;
    }
    double r = a / 2.0;                       // радіус кола
    double d2 = x * x + (y + r) * (y + r);    // квадрат відстані до центру кола
    bool inCircle  = d2 < r * r;
    bool outCircle = d2 > r * r;
    bool inSquare  = fabs(x) < r && y < 0 && y > -a;
    bool below = y < x - r;                   // нижче діагоналі
    bool above = y > x - r;                   // вище діагоналі

    bool part1 = inCircle && below && x < 0;
    bool part2 = inSquare && outCircle && below && y > -r;
    bool part3 = inSquare && outCircle && above && y < -r;

    if (part1 || part2 || part3)
        cout << "Точка належить коричневій області." << endl;
    else
        cout << "Точка НЕ належить коричневій області." << endl;
}
